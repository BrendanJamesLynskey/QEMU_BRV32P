#!/usr/bin/env python3
"""gen_random.py - randomised operand tests of the BRV32P custom instructions.

Usage: tests/gen_random.py <outdir> [seed]

Writes one assembly file per instruction group into <outdir>, each a
riscv-tests style test that runs through `tohost` (pass = 1). The files hold
no expected values: tests/run_lockstep.sh runs each on QEMU and on Spike (with
the core repo's libxbrvdsp.so) and tests/lockstep_qemu.py compares every
retired instruction and register write. What a file stores to memory is the
result of each instruction, for a record and for a look in a debugger.

  rand_alu.S   mac dmac msu acc.set acc.seth acc.rd acc.rdh acc.rdl acc.rdx
               sadd ssub radd16 rsub16 pk16
  rand_gf.S    gfmul4 gf.cfg gf.rd with the Reed-Solomon, AES and random polynomials
  rand_mq.S    mqmul2 mqadd2 mqsub2 ctadd2 ctsub2 gsmul2 mq.cfg mq.zeta mq.rd mq.rdz
  rand_agu.S   ar.set ar.cfg ar.mode ar.rd ar.rds ar.rdm lh.a lw.a lhu.a, plain and bit-reversed
  rand_loop.S  lp.setup lp.set lp.sets lp.rd lp.rds lp.end mac.lp dmac.lp msu.lp

Every group runs a few hundred operand sets per instruction; the operands are
random with a bias towards the edges (0, -1, the 16- and 32-bit limits).
"""
import os
import random
import sys

N = 256                       # operand sets per instruction

# name -> (opcode, funct3, funct7, form)
#   rrd: rd, rs1, rs2   rr: rs1, rs2   r: rs1   d: rd
OPS = {
    "MAC": ("CUSTOM_0", 0, 0x00, "rr"), "DMAC": ("CUSTOM_0", 0, 0x01, "rr"),
    "MSU": ("CUSTOM_0", 0, 0x02, "rr"),
    "MAC_LP": ("CUSTOM_0", 0, 0x40, "rr"), "DMAC_LP": ("CUSTOM_0", 0, 0x41, "rr"),
    "MSU_LP": ("CUSTOM_0", 0, 0x42, "rr"),
    "ACC_SET": ("CUSTOM_0", 0, 0x04, "r"), "ACC_SETH": ("CUSTOM_0", 0, 0x05, "r"),
    "ACC_RDL": ("CUSTOM_0", 3, 0x00, "d"), "ACC_RDX": ("CUSTOM_0", 3, 0x01, "d"),
    "SADD": ("CUSTOM_0", 4, 0x00, "rrd"), "SSUB": ("CUSTOM_0", 4, 0x01, "rrd"),
    "RADD16": ("CUSTOM_0", 4, 0x02, "rrd"), "RSUB16": ("CUSTOM_0", 4, 0x03, "rrd"),
    "PK16": ("CUSTOM_0", 4, 0x04, "rrd"),
    "GFMUL4": ("CUSTOM_0", 5, 0x00, "rrd"), "GF_CFG": ("CUSTOM_0", 5, 0x01, "r"),
    "GF_RD": ("CUSTOM_0", 5, 0x02, "d"),
    "MQMUL2": ("CUSTOM_0", 6, 0x00, "rrd"), "MQADD2": ("CUSTOM_0", 6, 0x01, "rrd"),
    "MQSUB2": ("CUSTOM_0", 6, 0x02, "rrd"), "CTADD2": ("CUSTOM_0", 6, 0x03, "rrd"),
    "CTSUB2": ("CUSTOM_0", 6, 0x04, "rrd"), "GSMUL2": ("CUSTOM_0", 6, 0x09, "rrd"),
    "MQ_CFG": ("CUSTOM_0", 6, 0x05, "r"), "MQ_ZETA": ("CUSTOM_0", 6, 0x06, "r"),
    "MQ_RD": ("CUSTOM_0", 6, 0x07, "d"), "MQ_RDZ": ("CUSTOM_0", 6, 0x08, "d"),
}


def insn(name, *regs):
    op, f3, f7, form = OPS[name]
    if form == "rrd":
        rd, a, b = regs
    elif form == "rr":
        rd, a, b = "x0", *regs
    elif form == "r":
        rd, a, b = "x0", regs[0], "x0"
    else:
        rd, a, b = regs[0], "x0", "x0"
    return f"  .insn r {op}, {f3}, {f7}, {rd}, {a}, {b}"


def acc_rd(rd, sh):
    return f"  .insn r CUSTOM_0, 1, 0, {rd}, x0, x{sh}"


def acc_rdh(rd, sh):
    return f"  .insn r CUSTOM_0, 2, 0, {rd}, x0, x{sh}"


def ar_set(n, rs):
    return f"  .insn r CUSTOM_1, 0, 0, x{n}, {rs}, x0"


def ar_cfg(n, rs):
    return f"  .insn r CUSTOM_1, 0, 1, x{n}, {rs}, x0"


def ar_mode(n, rs):
    return f"  .insn r CUSTOM_1, 0, 3, x{n}, {rs}, x0"


def ar_ld(kind, rd, n):                    # lh.a lw.a lhu.a
    f3 = {"lh": 1, "lw": 2, "lhu": 5}[kind]
    return f"  .insn i CUSTOM_1, {f3}, {rd}, x0, {n}"


def ar_rd(rd, n, what):                    # addr, stride, mode
    imm = {"rd": n, "rds": n + 4, "rdm": n + 12}[what]
    return f"  .insn i CUSTOM_1, 3, {rd}, x0, {imm}"


def lp_setup(rs):
    return f"  .insn i CUSTOM_1, 6, x0, {rs}, 0"


def lp_set(rs):
    return f"  .insn r CUSTOM_1, 0, 2, x0, {rs}, x0"


def lp_sets(rs):
    return f"  .insn r CUSTOM_1, 0, 2, x1, {rs}, x0"


def lp_rd(rd):
    return f"  .insn i CUSTOM_1, 3, {rd}, x0, 8"


def lp_rds(rd):
    return f"  .insn i CUSTOM_1, 3, {rd}, x0, 9"


LP_END = "  .insn i CUSTOM_1, 7, x0, x0, 0"

EDGES = [0, 1, 0xFFFFFFFF, 0x7FFFFFFF, 0x80000000, 0x7FFF, 0x8000, 0xFFFF, 0x10000,
         0xFFFF8000, 0x00007FFF, 0x80008000, 0x7FFF7FFF, 0x0001FFFF, 0xFFFF0001,
         0x0D01, 0x0D00, 0x0CFF, 0x0D010D01, 0x80, 0xFF, 0x01010101, 0xFF00FF00]


def rnd32(rng):
    r = rng.random()
    if r < 0.2:
        return rng.choice(EDGES)
    if r < 0.35:                            # two small lanes, as mod-q data
        return rng.randrange(3329) | rng.randrange(3329) << 16
    if r < 0.45:                            # small signed halves
        return (rng.randrange(-300, 300) & 0xFFFF) | (rng.randrange(-300, 300) & 0xFFFF) << 16
    return rng.getrandbits(32)


def header(title):
    return f"""/*
 * {title}
 * Generated by tests/gen_random.py: random operands, no expected values; the
 * check is the instruction-by-instruction comparison with Spike
 * (tests/run_lockstep.sh).
 */

#include "riscv_test.h"
#include "test_macros.h"

RVTEST_RV32U
RVTEST_CODE_BEGIN

  li TESTNUM, 2                 # nonzero, so that TEST_PASSFAIL passes
"""


def footer(data):
    return f"""
  TEST_PASSFAIL

RVTEST_CODE_END

  .data
RVTEST_DATA_BEGIN
  TEST_DATA
  .align 4
{data}
RVTEST_DATA_END
"""


def table(rng, label, n=N, words=4):
    out = [f"{label}:"]
    for _ in range(n):
        out.append("  .word " + ", ".join(f"0x{rnd32(rng):08x}" for _ in range(words)))
    return "\n".join(out)


def loop_binop(name, res, count=N, store=True, alias=None, pre=()):
    """for i in count: a1, a2 = table[i]; res[i] = op(a1, a2)"""
    dest = alias or "a0"
    lines = ["  la t0, ops"] + ([f"  la t1, {res}"] if store else []) + [f"  li t2, {count}", "1:",
                                                                      "  lw a1, 0(t0)", "  lw a2, 4(t0)"]
    lines += list(pre)
    lines += [insn(name, dest, "a1", "a2")]
    if store:
        lines += [f"  sw {dest}, 0(t1)", "  addi t1, t1, 4"]
    else:
        lines += [f"  xor s2, s2, {dest}", f"  add s3, s3, {dest}"]
    lines += ["  addi t0, t0, 16", "  addi t2, t2, -1", "  bnez t2, 1b"]
    return "\n".join(lines)


# ---- MAC, saturating and packed arithmetic ----
def gen_alu(rng):
    body = [header("rand_alu.S - random operands: the accumulator, saturating and packed arithmetic")]
    body.append("  li s2, 0\n  li s3, 0")
    res = []
    for name in ("SADD", "SSUB", "RADD16", "RSUB16", "PK16"):
        lab = f"res_{name.lower()}"
        body.append(loop_binop(name, lab))
        res.append(f"{lab}:\n  .space {4 * N}")
    # aliasing: rd = rs1 and rd = rs2 (a1 or a2 is the destination)
    for name in ("SADD", "SSUB", "RADD16", "RSUB16", "PK16"):
        body.append(loop_binop(name, "res_alias", count=64, store=False, alias="a1"))
        body.append(loop_binop(name, "res_alias", count=64, store=False, alias="a2"))
    # accumulate: set, three kinds of multiply-accumulate, read back
    body.append("  la t0, ops\n  la t1, res_acc\n  li t2, %d\n1:" % N)
    body += ["  lw a1, 0(t0)", "  lw a2, 4(t0)", "  lw a3, 8(t0)", "  lw a4, 12(t0)",
             insn("ACC_SET", "a3"), insn("ACC_SETH", "a4"),
             insn("MAC", "a1", "a2"), insn("ACC_RDL", "a0"), "  sw a0, 0(t1)",
             insn("ACC_RDX", "a0"), "  sw a0, 4(t1)",
             insn("DMAC", "a1", "a2"), insn("ACC_RDL", "a0"), "  sw a0, 8(t1)",
             insn("ACC_RDX", "a0"), "  sw a0, 12(t1)",
             insn("MSU", "a2", "a3"), insn("ACC_RDL", "a0"), "  sw a0, 16(t1)",
             insn("ACC_RDX", "a0"), "  sw a0, 20(t1)",
             insn("DMAC", "a3", "a4"), insn("MAC", "a2", "a2"),
             insn("MSU", "a4", "a1"), insn("ACC_RDL", "a0"), "  sw a0, 24(t1)",
             insn("ACC_RDX", "a0"), "  sw a0, 28(t1)",
             "  addi t0, t0, 16", "  addi t1, t1, 32", "  addi t2, t2, -1", "  bnez t2, 1b"]
    res.append(f"res_acc:\n  .space {32 * N}")
    # round, shift and saturate: acc.rd and acc.rdh at a spread of shifts, each
    # over every operand set (a running sum and xor of the results is kept)
    for sh in (0, 1, 2, 3, 7, 8, 15, 16, 17, 24, 30, 31):
        for fn, tag in ((acc_rd, "rd"), (acc_rdh, "rdh")):
            body += ["  la t0, ops", f"  li t2, {N}", "1:",
                     "  lw a3, 8(t0)", "  lw a4, 12(t0)", "  lw a1, 0(t0)", "  lw a2, 4(t0)",
                     insn("ACC_SET", "a3"), insn("ACC_SETH", "a4"),
                     insn("DMAC", "a1", "a2"),          # a 40-bit value, not just a sign-extended word
                     fn("a0", sh), "  xor s2, s2, a0", "  add s3, s3, a0",
                     "  addi t0, t0, 16", "  addi t2, t2, -1", "  bnez t2, 1b"]
    body.append("  la t0, res_sum\n  sw s2, 0(t0)\n  sw s3, 4(t0)")
    res.append("res_sum:\n  .space 8")
    res.append("res_alias:\n  .space 4")
    return "\n".join(body) + footer(table(rng, "ops") + "\n" + "\n".join(res))


# ---- GF(2^8) ----
def gen_gf(rng):
    body = [header("rand_gf.S - random operands: gfmul4, gf.cfg, gf.rd")]
    body.append("  li s2, 0\n  li s3, 0")
    res = []
    polys = [0x1D, 0x1B, 0x00, 0xFF, 0x01, 0x87] + [rng.randrange(256) for _ in range(6)]
    for i, p in enumerate(polys):
        body.append(f"  li a5, 0x{p:x}\n" + insn("GF_CFG", "a5") + "\n" + insn("GF_RD", "a6") +
                    f"\n  la t0, res_poly\n  sw a6, {4 * i}(t0)")
        lab = f"res_gf{i}"
        body.append(loop_binop("GFMUL4", lab))
        res.append(f"{lab}:\n  .space {4 * N}")
    body.append("  li a5, 0x1d\n" + insn("GF_CFG", "a5"))
    for alias in ("a1", "a2"):
        body.append(loop_binop("GFMUL4", "res_alias", count=128, store=False, alias=alias))
    res.append(f"res_poly:\n  .space {4 * len(polys)}")
    res.append("res_alias:\n  .space 4")
    return "\n".join(body) + footer(table(rng, "ops") + "\n" + "\n".join(res))


# ---- mod q ----
def gen_mq(rng):
    body = [header("rand_mq.S - random operands: the mod-q instructions, for several q and q'")]
    body.append("  li s2, 0\n  li s3, 0")
    res = []

    def qp_for(q):                                 # -q^-1 mod 2^16, for odd q
        return (-pow(q, -1, 1 << 16)) & 0xFFFF

    cfgs = [(3329, 3327), (12289, qp_for(12289)), (7681, qp_for(7681)),
            (rng.randrange(1, 65536) | 1, rng.getrandbits(16)),      # a q' that is not -q^-1
            (0, 0), (65535, 65535), (1, 1), (40961, qp_for(40961))]
    ops = ("MQMUL2", "MQADD2", "MQSUB2", "CTADD2", "CTSUB2", "GSMUL2")
    for ci, (q, qp) in enumerate(cfgs):
        word = (qp << 16) | q
        body.append(f"  li a5, 0x{word:08x}\n" + insn("MQ_CFG", "a5") + "\n" + insn("MQ_RD", "a6") +
                    "\n" + insn("MQ_RDZ", "a7") +
                    f"\n  la t0, res_cfg\n  sw a6, {8 * ci}(t0)\n  sw a7, {8 * ci + 4}(t0)")
        for name in ops:
            lab = f"res_{name.lower()}_{ci}"
            keep = ci == 0                               # the default q keeps every result
            # a fresh zeta for every operand set, read back with mq.rdz
            pre = ["  lw a3, 8(t0)", insn("MQ_ZETA", "a3"), insn("MQ_RDZ", "a4"),
                   "  xor s2, s2, a4"]
            body.append(loop_binop(name, lab, store=keep, pre=pre))
            if keep:
                res.append(f"{lab}:\n  .space {4 * N}")
    res.append(f"res_cfg:\n  .space {8 * len(cfgs)}")
    # restore the default, read it back
    body.append("  li a5, 0xcff0d01\n" + insn("MQ_CFG", "a5") + "\n" + insn("MQ_RD", "a6"))
    return "\n".join(body) + footer(table(rng, "ops") + "\n" + "\n".join(res))


# ---- address registers ----
def gen_agu(rng):
    body = [header("rand_agu.S - random start, stride and load kind through the four address registers")]
    body.append("  la s0, buf\n  la s4, res")
    nres = 0

    def store(reg):
        nonlocal nres
        nres += 1
        return f"  sw {reg}, 0(s4)\n  addi s4, s4, 4"

    def reads(n):
        out = []
        for what in ("rd", "rds", "rdm"):
            out += [ar_rd("a0", n, what), store("a0")]
        return out

    # plain mode: strides in bytes, a multiple of 4 for lw.a, of 2 otherwise
    for case in range(56):
        n = rng.randrange(4)
        kinds = ["lw"] if rng.random() < 0.4 else ["lh", "lhu"]
        unit = 4 if kinds[0] == "lw" else 2
        stride = rng.choice([0, 1, -1, 2, -2, 3, 5, 7, 8, -8, 12, -12, 16, 20, -24, 31, -31]) * unit
        start = rng.randrange(2048, 6144, unit)
        body.append(f"  li a1, {start}\n  add a1, s0, a1\n" + ar_set(n, "a1") +
                    f"\n  li a2, {stride}\n" + ar_cfg(n, "a2") + "\n" + ar_mode(n, "x0"))
        for _ in range(8):
            body += [ar_ld(rng.choice(kinds), "a0", n), store("a0")]
        body += reads(n)
    # bit-reversed mode: a positive stride below 8 KB, inside the 8 KB buffer
    for case in range(32):
        n = rng.randrange(4)
        kind = rng.choice(("lh", "lw", "lhu"))
        unit = 4 if kind == "lw" else 2
        stride = rng.choice([0x1000, 0x800, 0x400, 0x200, 0x100, 0x80, 0x40, 0x20, 0x10, 8, 4,
                             rng.randrange(1, 0x2000)])
        start = rng.randrange(0, 8192, unit)
        body.append(f"  li a1, {start}\n  add a1, s0, a1\n" + ar_set(n, "a1") +
                    f"\n  li a2, {stride}\n" + ar_cfg(n, "a2") + "\n  li a3, 1\n" + ar_mode(n, "a3"))
        for _ in range(8):
            body += [ar_ld(kind, "a0", n), store("a0")]
        body += reads(n)
    data = "  .align 13\nbuf:\n" + "\n".join(
        "  .word " + ", ".join(f"0x{rng.getrandbits(32):08x}" for _ in range(8)) for _ in range(256)) + \
        f"\nres:\n  .space {4 * nres + 16}"
    return "\n".join(body) + footer(data)


# ---- hardware loop ----
def gen_loop(rng):
    body = [header("rand_loop.S - random counts and bodies through the hardware loop")]
    body.append("  la s0, ops\n  li s2, 0\n  la s4, res\n  li a3, 0\n" + insn("ACC_SET", "x0") +
                "\n  li a1, 0x40002\n  li a2, 0x30005")
    nres = 0
    counts = [0, 1, 2, 3, 4, 5, 7, 10, 17, 40]

    def store(reg):
        nonlocal nres
        nres += 1
        return f"  sw {reg}, 0(s4)\n  addi s4, s4, 4"

    for case in range(120):
        cnt = rng.choice(counts) if rng.random() < 0.7 else rng.randrange(0, 61)
        shape = rng.randrange(7)
        use_sets = rng.random() < 0.5
        lab = f"L{case}"
        # operands from the table
        body.append(f"  lw a1, {16 * (case % N)}(s0)\n  lw a2, {16 * (case % N) + 4}(s0)\n  lw a3, {16 * (case % N) + 8}(s0)")
        body.append(f"  li t1, {cnt}")
        if use_sets:
            body.append(f"  la t0, {lab}\n" + lp_sets("t0") + "\n" + lp_set("t1"))
        else:
            body.append(lp_setup("t1"))
        body.append(f"{lab}:" if use_sets else "")
        if shape == 0:                                 # one instruction body
            body.append(insn(rng.choice(["MAC_LP", "DMAC_LP", "MSU_LP"]), "a1", "a2"))
        elif shape == 1:                               # a load, then a multiply-accumulate
            n = rng.randrange(4)
            body.append(f"  andi t2, a3, 0x7f0\n  add t2, s0, t2\n" + ar_set(n, "t2"))
            body.append(f"  li t2, 4\n" + ar_cfg(n, "t2") + "\n" + ar_mode(n, "x0"))
            body.append(f"  la t0, {lab}_b\n" + lp_sets("t0") + "\n" + lp_set("t1") + f"\n{lab}_b:")
            body.append(ar_ld("lw", "a4", n))
            body.append(insn(rng.choice(["MAC_LP", "DMAC_LP", "MSU_LP"]), "a4", "a1"))
        elif shape == 2:                               # lp.end after other work
            body.append(insn("SADD", "a4", "a1", "a2"))
            body.append(insn("PK16", "a1", "a4", "a2"))
            body.append(LP_END)
        elif shape == 3:                               # read the count inside the loop
            body.append(lp_rd("a4"))
            body.append("  add s2, s2, a4")
            body.append(insn("MAC", "a1", "a2"))
            body.append(insn("DMAC_LP", "a2", "a1"))
        elif shape == 4:                               # read the start inside the loop
            body.append(lp_rds("a5"))
            body.append("  sub a5, a5, t0" if use_sets else "  addi a5, a5, 0")
            body.append("  add s2, s2, a5")
            body.append(LP_END)
        elif shape == 5:                               # a branch inside the body
            body.append("  andi a4, a3, 1")
            body.append(f"  beqz a4, {lab}_s")
            body.append(insn("MAC", "a1", "a1"))
            body.append(f"{lab}_s:")
            body.append(insn("MSU_LP", "a2", "a3"))
        else:                                          # a store and a GF multiply
            body.append(insn("GFMUL4", "a4", "a1", "a2"))
            body.append("  add s2, s2, a4")
            body.append(insn("MAC_LP", "a4", "a4"))
        body.append(lp_rd("a0"))                       # the count after the loop: 0
        body.append(store("a0"))
        body.append(insn("ACC_RDL", "a0"))
        body.append(store("a0"))
        body.append(insn("ACC_RDX", "a0"))
        body.append(store("a0"))
        body.append(store("s2"))
        # re-seed the accumulator, sometimes
        if case % 5 == 4:
            body.append(insn("ACC_SET", "a3"))
    data = table(rng, "ops") + f"\nres:\n  .space {4 * nres + 16}"
    return "\n".join(l for l in body if l != "") + footer(data)


def main():
    out = sys.argv[1]
    seed = int(sys.argv[2]) if len(sys.argv) > 2 else 20261104
    os.makedirs(out, exist_ok=True)
    for name, fn in (("rand_alu", gen_alu), ("rand_gf", gen_gf), ("rand_mq", gen_mq),
                     ("rand_agu", gen_agu), ("rand_loop", gen_loop)):
        rng = random.Random(f"{seed}-{name}")
        with open(os.path.join(out, name + ".S"), "w") as f:
            f.write(fn(rng))
        print("wrote", os.path.join(out, name + ".S"))


if __name__ == "__main__":
    main()
