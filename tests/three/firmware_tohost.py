#!/usr/bin/env python3
"""firmware_tohost.py <firmware.hex> <out.S> - the SoC firmware as an ELF source that ends through tohost.

The core repo's firmware (firmware/firmware.hex, made by gen_firmware.py) is a straight-line program that
ends in an ECALL: with mtvec = 0 the trap restarts it, and the testbench judges it by looking at the
registers. It never stores to tohost, so no simulator but the core repo's own testbench can tell when it is
done. This writes the same instruction words, up to but not including the ECALL, as a .S file, followed by
a check of the registers it computed and the store to tohost. Nothing in the core repo is changed.

The firmware's first words are placed at 0x80000000 (the core's ISA link script); it is position
independent, and its data at 0x4000 aliases the SRAM on every platform.
"""
import sys

words = [int(line, 16) for line in open(sys.argv[1]) if line.strip()]
ECALL = 0x00000073
cut = words.index(ECALL)

# register -> the value the firmware computes (see the comments in gen_firmware.py)
EXPECT = {3: 52, 4: 32, 5: 52, 6: 0x55, 7: 0xAA, 8: 160, 9: 40, 11: 52, 12: 0x55,
          15: 2, 17: 3, 18: 1, 19: 1, 25: 53}

out = ["/* Generated by tests/three/firmware_tohost.py from the core repo's firmware.hex: do not edit. */",
       "  .section .text.init", "  .globl _start", "_start:"]
for i, w in enumerate(words[:cut]):
    out.append(f"  .word 0x{w:08x}                  # {i * 4:#06x}")
out.append("  # the ECALL that restarts the firmware is replaced by a check and the store to tohost")
for reg, val in EXPECT.items():
    out.append(f"  li s11, {val}")
    out.append(f"  bne x{reg}, s11, fail")
out += ["  li s11, 1", "  la s10, tohost", "  sw s11, 0(s10)", "1: j 1b",
        "fail:", "  li s11, 3", "  la s10, tohost", "  sw s11, 0(s10)", "2: j 2b",
        "", '  .section .tohost, "aw", @progbits', "  .align 6", "  .globl tohost", "tohost: .dword 0",
        "  .align 6", "  .globl fromhost", "fromhost: .dword 0", ""]
open(sys.argv[2], "w").write("\n".join(out))

# The pcs whose result differs by design between platforms: a read of mcycle or minstret
# (csrrs rd, 0xB00 / 0xB02, x0); the runner tells the comparer to skip the value there
with open(sys.argv[2] + ".ignore", "w") as f:
    for i, w in enumerate(words[:cut]):
        if w & 0xFFFFF07F in (0xB0002073, 0xB0202073):
            f.write(f"0x{0x80000000 + 4 * i:08x}\n")
